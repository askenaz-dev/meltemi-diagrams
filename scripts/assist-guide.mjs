// Writes packages/assist/src/guide.ts from the agent skill's language references, so assistance
// and agents learn the language from the same pages. Run with `pnpm assist:guide`; a test in
// packages/assist fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The references every request carries, then the ones a profile adds. */
export const GUIDE_PAGES = ["language", "sequence", "c4", "free", "stories"];

export function guideSource(root) {
  const pages = GUIDE_PAGES.map((name) => [
    name,
    readFileSync(join(root, "skills", "meltemi-diagrams", "reference", `${name}.md`), "utf8"),
  ]);
  return [
    "// Generated by `pnpm assist:guide` from skills/meltemi-diagrams/reference; do not edit.",
    "",
    "/** The language references of the agent skill, by page. */",
    "export const GUIDE_PAGES: Readonly<Record<string, string>> = {",
    ...pages.map(([name, text]) => `  ${name}: ${JSON.stringify(text)},`),
    "};",
    "",
  ].join("\n");
}

if (
  process.argv[1] &&
  import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop())
) {
  const file = join(process.cwd(), "packages", "assist", "src", "guide.ts");
  writeFileSync(file, guideSource(process.cwd()));
  console.log(`Wrote ${file}`);
}
