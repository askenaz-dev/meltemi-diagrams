#!/usr/bin/env node
// Writes THIRD_PARTY_LICENSES.md from the production dependencies of the workspace packages.
// Usage: node scripts/licenses.mjs [--check]   (--check exits with 1 when the file is stale)
import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const target = join(root, "THIRD_PARTY_LICENSES.md");
const check = process.argv.includes("--check");

/** Packages whose files end up inside exported diagrams. */
const EMBEDDED = new Set([
  "@fontsource/inter",
  "@fontsource/ibm-plex-sans",
  "@fontsource/cascadia-mono",
  "@fontsource/patrick-hand",
  "inter-ui",
  "@ibm/plex-sans",
]);

/** Licence choices and obligations, by package (see docs/decisions). */
const NOTES = new Map([
  [
    "elkjs",
    "used under EPL-2.0, unmodified; source: https://github.com/kieler/elkjs (decision 0015)",
  ],
]);

const report = JSON.parse(execSync("pnpm licenses list --prod --json", { encoding: "utf8" }));
const rows = [];
for (const [license, packages] of Object.entries(report)) {
  for (const pkg of packages) {
    if (pkg.name.startsWith("@meltemi/")) continue;
    for (const version of pkg.versions) {
      rows.push({ name: pkg.name, version, license, homepage: pkg.homepage ?? "" });
    }
  }
}
rows.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : 1));

const cell = (text) => String(text).replace(/\|/g, "\\|");

// The vendor icon sets bundled from packages/assets/vendor, under their own terms.
const vendorFolder = join(root, "packages", "assets", "vendor");
const sets = existsSync(vendorFolder)
  ? readdirSync(vendorFolder)
      .filter((f) => f.endsWith(".json") && f !== "index.json")
      .sort()
      .map((file) => {
        const info = JSON.parse(readFileSync(join(vendorFolder, file), "utf8")).info ?? {};
        return {
          name: info.name ?? file,
          version: info.version ?? "",
          license: info.license?.spdx ?? info.license?.title ?? "",
          url: info.license?.url ?? info.author?.url ?? "",
          terms: info.terms ?? "",
        };
      })
  : [];
const lines = [
  "# Third-party licenses",
  "",
  "Meltemi Diagrams' own code is MIT. The packages below are production dependencies of the",
  "workspace and keep their own licenses. This file is generated by `pnpm licenses:inventory`;",
  "CI checks that it is current.",
  "",
  "Fonts marked _embedded_ are bundled with the tool and embedded in exported diagrams (subsets,",
  "or glyph outlines), which the SIL Open Font License 1.1 permits.",
  "",
  "| Package | Version | License | Notes | Homepage |",
  "| --- | --- | --- | --- | --- |",
  ...rows.map(
    (r) =>
      `| ${cell(r.name)} | ${cell(r.version)} | ${cell(r.license)} | ${cell(NOTES.get(r.name) ?? (EMBEDDED.has(r.name) ? "embedded" : ""))} | ${cell(r.homepage)} |`,
  ),
  "",
  "## Bundled icon sets",
  "",
  "The provider icon sets below are converted unmodified from the vendors' downloads by",
  "`pnpm vendor:icons` into `packages/assets/vendor/` and bundled with the tool under the",
  "vendors' own terms, which every host repeats in its notices.",
  "",
  "| Set | Version | License | Terms | Source |",
  "| --- | --- | --- | --- | --- |",
  ...sets.map(
    (s) =>
      `| ${cell(s.name)} | ${cell(s.version)} | ${cell(s.license)} | ${cell(s.terms)} | ${cell(s.url)} |`,
  ),
  "",
];
const text = lines.join("\n");

if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== text) {
    const listed = new Set(
      current
        .split("\n")
        .filter((l) => l.startsWith("| ") && !l.startsWith("| Package") && !l.startsWith("| ---"))
        .map((l) => l.split("|")[1].trim()),
    );
    const missing = [...new Set(rows.map((r) => r.name))].filter((n) => !listed.has(n));
    console.error(
      `THIRD_PARTY_LICENSES.md is stale${missing.length > 0 ? `; missing: ${missing.join(", ")}` : ""}. Run pnpm licenses:inventory.`,
    );
    process.exit(1);
  }
  console.log(`THIRD_PARTY_LICENSES.md is current (${rows.length} packages).`);
} else {
  writeFileSync(target, text);
  console.log(`Wrote THIRD_PARTY_LICENSES.md (${rows.length} packages).`);
}
