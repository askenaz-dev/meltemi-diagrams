// Writes `src/renderer-bundle.js`: the import of every file the renderer object carries, as data
// (fonts), text (JSON) and compiled WebAssembly (resvg) modules of the Worker, by the `rules` of
// `wrangler.jsonc`. It is JavaScript with a declaration beside it (`renderer-bundle.d.ts`), so that
// TypeScript reads the declared types rather than the JSON files themselves. The font files are those
// the command line's font library reads for the four measured families (`MEASURED_FAMILIES`), found
// as `bundledFontFiles()` finds them for the page (`isMeasuredFontPath`, which the local server's
// engine reads by too).
//
//   tsx --conditions=@meltemi/diagrams-source packages/cloud/scripts/renderer-bundle.ts [--check]
//
// `--check` writes nothing and fails when the file is not what it would write; a test does the same.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { bundledFontFiles } from "@meltemi/diagrams-fonts/node";
import { isMeasuredFontPath } from "@meltemi/diagrams-mcp/node";
import { format, resolveConfig } from "prettier";
import { ASSET_FILES, RASTER_FILES, type BundledFile } from "../src/renderer-files.js";

/** The cloud package's folder. */
export const CLOUD = fileURLToPath(new URL("../", import.meta.url));
export const BUNDLE_FILE = fileURLToPath(new URL("../src/renderer-bundle.js", import.meta.url));

/**
 * The font files the library reads to measure the four families: a family's complete files when it
 * has them (Inter, IBM Plex Sans), else its subset table and the subsets of its weights.
 */
export function measuredFontFiles(): BundledFile[] {
  return bundledFontFiles()
    .filter((file) => isMeasuredFontPath(file.path))
    .map((file) => ({ path: file.path, source: `node_modules/${file.path}` }));
}

/** The specifier of a file of the bundle, from `src/`. */
const specifier = (file: BundledFile) => `../${file.source}`;

/** The text of `src/renderer-bundle.js`, formatted as the repository formats it. */
export async function rendererBundleSource(): Promise<string> {
  const lines = [
    "// Generated by `scripts/renderer-bundle.ts` from `renderer-files.ts`; do not edit: run",
    "// `pnpm cloud:renderer-bundle`. The files the renderer object carries, as modules of the Worker",
    "// (`rules` in wrangler.jsonc): fonts as data, JSON as text, resvg as compiled WebAssembly. They",
    "// are imported when `loadBundle` is called, the first time an object draws: a module imported",
    "// statically would be instantiated by every isolate of the Worker, drawing or not.",
    "",
    "/** The modules' default exports, keyed as the engine reads them. */",
    "const keyed = async (entries) =>",
    "  Object.fromEntries(",
    "    await Promise.all(entries.map(async ([path, load]) => [path, (await load()).default])),",
    "  );",
    "",
    "export async function loadBundle() {",
    "  const [fonts, raster, assets, wasm, manifest] = await Promise.all([",
  ];
  const group = (list: readonly BundledFile[]) => {
    lines.push("    keyed([");
    for (const file of list) {
      lines.push(`      [${JSON.stringify(file.path)}, () => import("${specifier(file)}")],`);
    }
    lines.push("    ]),");
  };
  group(measuredFontFiles());
  group(RASTER_FILES);
  group(ASSET_FILES);
  lines.push('    import("../node_modules/@resvg/resvg-wasm/index_bg.wasm"),');
  lines.push('    import("../package.json"),');
  lines.push("  ]);");
  lines.push("  return {");
  lines.push("    fonts,");
  lines.push("    raster,");
  lines.push("    assets,");
  lines.push("    wasm: wasm.default,");
  lines.push("    toolVersion: JSON.parse(manifest.default).version,");
  lines.push("  };");
  lines.push("}");
  const options = (await resolveConfig(BUNDLE_FILE)) ?? {};
  return format(`${lines.join("\n")}\n`, { ...options, filepath: BUNDLE_FILE });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const text = await rendererBundleSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(BUNDLE_FILE, "utf8") !== text) {
      console.error("src/renderer-bundle.js is stale: run pnpm cloud:renderer-bundle");
      process.exit(1);
    }
  } else {
    writeFileSync(BUNDLE_FILE, text);
    console.log(`wrote ${BUNDLE_FILE}`);
  }
}
